# Buat program untuk perulangan for dalam Python
# Nama variabel ditambah 4 digit nim terakhir contoh: ulang_2004
# Program ini menggunakan fungsi input()

ulang_2004 = int(input("Masukkan jumlah perulangan: "))
print("Perulangan ke-0 sampai ke-", ulang_2004-1)
for i_2004 in range(ulang_2004):
    print(i_2004, end=" ")
print()
print("Perulangan ke-1 sampai ke-", ulang_2004)
for i_2004 in range(1, ulang_2004 + 1):
    print(i_2004, end=" ")