# Nama variabel ditambah 4 digit nim terakhir contoh: ipk_2004
# Program ini menggunakan fungsi input()
# program konversi nilai angka menjadi huruf

nilai_2004 = int(input("Inputkan nilai angka= "))

if nilai_2004 >= 81:
    print("A")
elif nilai_2004 >= 70:
    print("B")
elif nilai_2004 >= 60:
    print("C")
elif nilai_2004 >= 50:
    print("D")
else:
    print("E")